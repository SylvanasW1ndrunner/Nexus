CREATE TABLE commerce.orders (
  order_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  order_no varchar(40) NOT NULL UNIQUE,
  user_id bigint NOT NULL REFERENCES iam.users(user_id),
  status commerce.order_status NOT NULL,
  currency char(3) NOT NULL DEFAULT 'CNY',
  subtotal_amount numeric(14,2) NOT NULL DEFAULT 0,
  discount_amount numeric(14,2) NOT NULL DEFAULT 0,
  shipping_fee numeric(14,2) NOT NULL DEFAULT 0,
  tax_amount numeric(14,2) NOT NULL DEFAULT 0,
  total_amount numeric(14,2) GENERATED ALWAYS AS (
    subtotal_amount - discount_amount + shipping_fee + tax_amount
  ) STORED,
  coupon_code varchar(40),
  shipping_address jsonb NOT NULL,
  channel varchar(20) NOT NULL,
  risk_score numeric(5,2) NOT NULL DEFAULT 0,
  notes text,
  ordered_at timestamptz NOT NULL,
  paid_at timestamptz,
  cancelled_at timestamptz,
  updated_at timestamptz NOT NULL,
  CONSTRAINT orders_amount_check CHECK (
    subtotal_amount >= 0 AND discount_amount >= 0 AND shipping_fee >= 0 AND tax_amount >= 0
      AND discount_amount <= subtotal_amount
  ),
  CONSTRAINT orders_channel_check CHECK (channel IN ('web', 'app', 'mini_program', 'api')),
  CONSTRAINT orders_risk_score_check CHECK (risk_score BETWEEN 0 AND 100),
  CONSTRAINT orders_shipping_address_object CHECK (jsonb_typeof(shipping_address) = 'object')
);

CREATE INDEX orders_user_time_idx ON commerce.orders (user_id, ordered_at DESC);
CREATE INDEX orders_status_time_idx ON commerce.orders (status, ordered_at DESC);
CREATE INDEX orders_shipping_address_gin_idx ON commerce.orders USING gin (shipping_address);

CREATE TABLE commerce.order_items (
  order_item_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL REFERENCES commerce.orders(order_id) ON DELETE CASCADE,
  variant_id bigint NOT NULL REFERENCES catalog.product_variants(variant_id),
  product_name_snapshot text NOT NULL,
  sku_snapshot varchar(80) NOT NULL,
  quantity integer NOT NULL,
  unit_price numeric(12,2) NOT NULL,
  discount_amount numeric(12,2) NOT NULL DEFAULT 0,
  line_total numeric(14,2) GENERATED ALWAYS AS (unit_price * quantity - discount_amount) STORED,
  attributes jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL,
  CONSTRAINT order_items_quantity_check CHECK (quantity > 0),
  CONSTRAINT order_items_amount_check CHECK (
    unit_price >= 0 AND discount_amount >= 0 AND discount_amount <= unit_price * quantity
  )
);

CREATE INDEX order_items_order_idx ON commerce.order_items (order_id);
CREATE INDEX order_items_variant_idx ON commerce.order_items (variant_id, created_at DESC);

