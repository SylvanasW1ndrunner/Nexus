CREATE VIEW analytics.customer_order_360 AS
WITH order_stats AS (
  SELECT
    user_id,
    count(*) AS order_count,
    count(*) FILTER (WHERE status = 'completed') AS completed_order_count,
    round(sum(total_amount), 2) AS lifetime_order_amount,
    max(ordered_at) AS last_order_at
  FROM commerce.orders
  GROUP BY user_id
), login_stats AS (
  SELECT
    user_id,
    count(*) FILTER (WHERE NOT success) AS failed_login_count_90d
  FROM iam.login_events
  WHERE occurred_at >= clock_timestamp() - interval '90 days'
  GROUP BY user_id
)
SELECT
  u.user_id,
  u.email,
  u.display_name,
  u.status AS user_status,
  u.profile ->> 'level' AS member_level,
  coalesce(os.order_count, 0) AS order_count,
  coalesce(os.completed_order_count, 0) AS completed_order_count,
  coalesce(os.lifetime_order_amount, 0) AS lifetime_order_amount,
  os.last_order_at,
  coalesce(ls.failed_login_count_90d, 0) AS failed_login_count_90d
FROM iam.users AS u
LEFT JOIN order_stats AS os ON os.user_id = u.user_id
LEFT JOIN login_stats AS ls ON ls.user_id = u.user_id;

CREATE VIEW streaming.kafka_event_quality AS
SELECT
  topic,
  event_type,
  parse_status,
  count(*) AS event_count,
  min(event_time) AS first_event_at,
  max(event_time) AS last_event_at,
  round(avg(extract(epoch FROM (ingested_at - event_time)) * 1000)::numeric, 2) AS avg_ingest_latency_ms
FROM streaming.raw_kafka_events
GROUP BY topic, event_type, parse_status;

