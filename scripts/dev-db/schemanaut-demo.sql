CREATE TABLE streaming.raw_kafka_events (
  kafka_event_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  topic varchar(120) NOT NULL,
  partition_no integer NOT NULL,
  offset_no bigint NOT NULL,
  event_key text,
  event_type varchar(60),
  headers jsonb NOT NULL DEFAULT '{}'::jsonb,
  value jsonb NOT NULL,
  event_time timestamptz,
  ingested_at timestamptz NOT NULL,
  schema_version integer NOT NULL DEFAULT 1,
  parse_status varchar(20) NOT NULL DEFAULT 'valid',
  UNIQUE (topic, partition_no, offset_no),
  CONSTRAINT kafka_partition_check CHECK (partition_no >= 0),
  CONSTRAINT kafka_offset_check CHECK (offset_no >= 0),
  CONSTRAINT kafka_value_object CHECK (jsonb_typeof(value) = 'object'),
  CONSTRAINT kafka_parse_status_check CHECK (parse_status IN ('valid', 'invalid', 'partial', 'duplicate'))
);

CREATE INDEX raw_kafka_topic_time_idx ON streaming.raw_kafka_events (topic, event_time DESC);
CREATE INDEX raw_kafka_event_type_idx ON streaming.raw_kafka_events (event_type, ingested_at DESC);
CREATE INDEX raw_kafka_value_gin_idx ON streaming.raw_kafka_events USING gin (value);
CREATE INDEX raw_kafka_invalid_idx ON streaming.raw_kafka_events (ingested_at DESC)
WHERE parse_status <> 'valid';

CREATE TABLE streaming.consumer_offsets (
  consumer_group varchar(120) NOT NULL,
  topic varchar(120) NOT NULL,
  partition_no integer NOT NULL,
  committed_offset bigint NOT NULL,
  high_watermark bigint NOT NULL,
  lag bigint GENERATED ALWAYS AS (high_watermark - committed_offset) STORED,
  consumer_instance varchar(120),
  updated_at timestamptz NOT NULL,
  PRIMARY KEY (consumer_group, topic, partition_no),
  CONSTRAINT consumer_offsets_order_check CHECK (
    partition_no >= 0 AND committed_offset >= 0 AND high_watermark >= committed_offset
  )
);

CREATE INDEX consumer_offsets_lag_idx ON streaming.consumer_offsets (lag DESC);

