  available_quantity integer NOT NULL,
  reserved_quantity integer NOT NULL,
  reorder_point integer NOT NULL,
  safety_stock integer NOT NULL,
  version integer NOT NULL DEFAULT 1,
  updated_at timestamptz NOT NULL,
